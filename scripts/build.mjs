#!/usr/bin/env node
/**
 * Builds every packages/plugin-* into build/<name>/ (a ready NocoBase plugin directory) and
 * build/<name>-<version>.tgz (uploadable through "Plugin manager -> Add -> Upload").
 * Also packs the supervisor into build/nocobase-multicore-supervisor-<version>.tgz.
 *
 * Needs only esbuild (no NocoBase monorepo): `ESBUILD=/path/to/esbuild node scripts/build.mjs`
 * or esbuild available as an npm package.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packagesDir = path.join(root, 'packages');
const buildDir = path.join(root, 'build');

async function loadEsbuild() {
  const candidates = [process.env.ESBUILD_MODULE, 'esbuild', '/opt/npm-tools/node_modules/esbuild/lib/main.js'].filter(Boolean);
  for (const candidate of candidates) {
    try {
      const mod = await import(candidate.startsWith('/') ? pathToFileURL(candidate).href : candidate);
      return mod.default?.build ? mod.default : mod;
    } catch (error) {
      // try next
    }
  }
  throw new Error('esbuild not found. npm i -D esbuild, or set ESBUILD_MODULE=/path/to/esbuild/lib/main.js');
}

const esbuild = await loadEsbuild();
fs.rmSync(buildDir, { recursive: true, force: true });
fs.mkdirSync(buildDir, { recursive: true });

const SERVER_EXTERNAL = ['@nocobase/*', 'redis', '@redis/*', 'sequelize'];
const CLIENT_EXTERNALS = ['react', 'antd', '@nocobase/client', '@ant-design/icons'];

const header = `/**\n * nocobase-multicore (AGPL-3.0-only). Generated by scripts/build.mjs - do not edit.\n */\n`;

/** UMD wrapper: NocoBase loads client bundles through requirejs (AMD) with react/antd/@nocobase/client provided. */
function umd(name, deps, cjsCode) {
  return `${header}(function (root, factory) {
  if (typeof exports === 'object' && typeof module === 'object') {
    module.exports = factory.apply(null, ${JSON.stringify(deps)}.map(function (d) { return require(d); }));
  } else if (typeof define === 'function' && define.amd) {
    define(${JSON.stringify(name)}, ${JSON.stringify(deps)}, factory);
  } else {
    var m = factory.apply(null, ${JSON.stringify(deps)}.map(function (d) { return root[d]; }));
    root[${JSON.stringify(name)}] = m;
  }
})(typeof self !== 'undefined' ? self : this, function () {
  var __deps = ${JSON.stringify(deps)};
  var __args = arguments;
  var module = { exports: {} };
  var require = function (id) { var i = __deps.indexOf(id); if (i < 0) throw new Error('multicore client: unexpected require ' + id); return __args[i]; };
  (function (module, exports, require) {
${cjsCode}
  })(module, module.exports, require);
  return module.exports;
});
`;
}

const externalVersionJs = (names) => `${header}// Versions are read from the HOST installation, so the compatibility check of the plugin manager always passes
// for the NocoBase version this plugin is installed into (supportedVersions is declared in package.json).
const names = ${JSON.stringify(names)};
const out = {};
for (const name of names) {
  try { out[name] = require(name + '/package.json').version; } catch (e) { /* not resolvable here: skip */ }
}
module.exports = out;
`;

const plugins = fs.readdirSync(packagesDir).filter((d) => d.startsWith('plugin-'));
const summary = [];

for (const dir of plugins) {
  const srcDir = path.join(packagesDir, dir);
  const pkg = JSON.parse(fs.readFileSync(path.join(srcDir, 'package.json'), 'utf8'));
  const out = path.join(buildDir, dir);
  fs.mkdirSync(path.join(out, 'dist', 'server'), { recursive: true });

  await esbuild.build({
    entryPoints: [path.join(srcDir, 'src/server/index.ts')],
    outfile: path.join(out, 'dist/server/index.js'),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    external: SERVER_EXTERNAL,
    minify: process.env.MINIFY === '1',
    banner: { js: process.env.MINIFY === '1' ? '' : header },
    logLevel: 'warning',
  });

  // NocoBase's web app requests dist/client/index.js of EVERY enabled plugin (a 404 there stops the whole UI with a
  // requirejs "Script error"), so server-only plugins get a minimal client stub.
  const clientFile = path.join(srcDir, 'src/client/index.tsx');
  const hasClient = fs.existsSync(clientFile);
  const externals = ['@nocobase/server'];
  fs.mkdirSync(path.join(out, 'dist', 'client'), { recursive: true });
  const clientCommon = {
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'cjs',
    target: 'es2020',
    jsx: 'transform',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    external: CLIENT_EXTERNALS,
    minify: true,
    logLevel: 'warning',
  };
  const result = await esbuild.build(
    hasClient
      ? { ...clientCommon, entryPoints: [clientFile] }
      : {
          ...clientCommon,
          stdin: {
            contents: "import { Plugin } from '@nocobase/client';\nexport class PluginStubClient extends Plugin {}\nexport default PluginStubClient;\n",
            resolveDir: root,
            loader: 'ts',
          },
        },
  );
  const clientDeps = hasClient ? CLIENT_EXTERNALS : ['@nocobase/client'];
  fs.writeFileSync(path.join(out, 'dist/client/index.js'), umd(pkg.name, clientDeps, result.outputFiles[0].text));
  fs.writeFileSync(path.join(out, 'dist/client/index.d.ts'), `export declare class PluginMulticoreClient {}\nexport default PluginMulticoreClient;\n`);
  fs.writeFileSync(path.join(out, 'client.js'), `module.exports = require('./dist/client/index.js');\n`);
  fs.writeFileSync(path.join(out, 'client.d.ts'), `export * from './dist/client';\nexport { default } from './dist/client';\n`);
  externals.push(...clientDeps);

  fs.writeFileSync(path.join(out, 'dist/externalVersion.js'), externalVersionJs(externals));
  fs.writeFileSync(path.join(out, 'dist/index.js'), `module.exports = require('./server');\n`);
  fs.writeFileSync(path.join(out, 'dist/server/index.d.ts'), `export declare const PluginServer: any;\nexport default PluginServer;\n`);
  fs.writeFileSync(path.join(out, 'server.js'), `module.exports = require('./dist/server/index.js');\n`);
  fs.writeFileSync(path.join(out, 'server.d.ts'), `export * from './dist/server';\nexport { default } from './dist/server';\n`);
  fs.copyFileSync(path.join(srcDir, 'package.json'), path.join(out, 'package.json'));
  fs.copyFileSync(path.join(root, 'LICENSE'), path.join(out, 'LICENSE'));

  const tgz = path.join(buildDir, `${pkg.name.replace('@', '').replace('/', '-')}-${pkg.version}.tgz`);
  execFileSync('tar', ['czf', tgz, '-C', out, '.']);
  summary.push(`${pkg.name}@${pkg.version} -> ${path.relative(root, tgz)}`);
}

// supervisor
const sup = path.join(packagesDir, 'supervisor');
const supPkg = JSON.parse(fs.readFileSync(path.join(sup, 'package.json'), 'utf8'));
const supOut = path.join(buildDir, 'supervisor');
fs.cpSync(sup, supOut, { recursive: true });
if (process.env.MINIFY === '1') {
  for (const rel of ['lib/config.js', 'lib/supervisor.js']) {
    const file = path.join(supOut, rel);
    fs.writeFileSync(file, esbuild.transformSync(fs.readFileSync(file, 'utf8'), { minify: true, target: 'node20' }).code);
  }
}
const supTgz = path.join(buildDir, `nocobase-multicore-supervisor-${supPkg.version}.tgz`);
execFileSync('tar', ['czf', supTgz, '-C', supOut, '.']);
summary.push(`${supPkg.name}@${supPkg.version} -> ${path.relative(root, supTgz)}`);

console.log(summary.join('\n'));
