#!/usr/bin/env bash
# Removes nocobase-multicore from NocoBase safely: switches the cluster off first, then disables and removes the plugins.
#   ./uninstall.sh --docker <container>   |   ./uninstall.sh --local <project-dir>
# If install.sh created docker-compose.multicore.yml (Redis + supervisor entrypoint), it is removed again and the app
# container is recreated with its original entrypoint - one command back to stock NocoBase.
# Option: --purge   ALSO delete storage/multicore (supervisor files + config) and the Redis data volume created by install.sh.
#                   Without the compose override created by install.sh, use it only AFTER you have put the original
#                   container entrypoint / start command back, otherwise the container can no longer start.
set -eu
MODE=""; TARGET=""; PURGE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --docker) MODE=docker; TARGET="${2:-}"; shift 2 ;;
    --local) MODE=local; TARGET="${2:-}"; shift 2 ;;
    --purge) PURGE=1; shift ;;
    -h|--help) sed -n 2,10p "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
[ -n "$MODE" ] && [ -n "$TARGET" ] || { sed -n 2,10p "$0"; exit 2; }
PLUGINS="plugin-multicore plugin-worker-id-allocator-redis plugin-queue-adapter-redis plugin-lock-adapter-redis plugin-pubsub-adapter-redis"
if [ "$MODE" = docker ]; then
  ROOT=/app/nocobase
  run_in() { docker exec -w "$ROOT" "$TARGET" "$@"; }
else
  ROOT=$(cd "$TARGET" && pwd)
  run_in() { (cd "$ROOT" && "$@"); }
fi
STORAGE="$ROOT/storage"

echo "== 1/4 switching cluster mode off (back to one process)"
run_in sh -c "mkdir -p storage/multicore && printf '{\"enabled\":false,\"workers\":1,\"updatedBy\":\"uninstall.sh\"}' > storage/multicore/config.json"
echo "   waiting for the supervisor to replace the workers (up to 90 s)..."
for _ in $(seq 1 30); do
  n=$(run_in sh -c 'cat storage/multicore/status.json 2>/dev/null' | grep -o '"mode": *"cluster"' | wc -l || true)
  [ "${n:-0}" = 0 ] && break
  sleep 3
done

echo "== 2/4 disabling plugins"
# shellcheck disable=SC2046
run_in yarn nocobase pm disable $(for p in $PLUGINS; do printf '@nb-multicore/%s ' "$p"; done) >/dev/null && echo "   disabled" || echo "   (some plugins were already disabled)"
echo "== 3/4 removing plugins"
for p in $PLUGINS; do run_in yarn nocobase pm remove "@nb-multicore/$p" >/dev/null 2>&1 && echo "   removed @nb-multicore/$p" || echo "   @nb-multicore/$p was not registered"; done
run_in sh -c 'rm -rf storage/plugins/@nb-multicore'
echo "== 4/4 compose override and files"
RESTORED=0
if [ "$MODE" = docker ]; then
  LABEL() { docker inspect -f "{{ index .Config.Labels \"$1\" }}" "$TARGET" 2>/dev/null; }
  PROJECT_DIR=$(LABEL com.docker.compose.project.working_dir); CONFIG_FILES=$(LABEL com.docker.compose.project.config_files)
  PROJECT=$(LABEL com.docker.compose.project); SERVICE=$(LABEL com.docker.compose.service)
  OVERRIDE="$PROJECT_DIR/docker-compose.multicore.yml"
  if [ -n "$PROJECT_DIR" ] && [ -f "$OVERRIDE" ] && head -1 "$OVERRIDE" | grep -q 'Generated by nocobase-multicore'; then
    rm -f "$OVERRIDE"
    if [ -f "$PROJECT_DIR/.env" ] && grep -q '^COMPOSE_FILE=.*docker-compose.multicore.yml' "$PROJECT_DIR/.env"; then
      sed -i -e '/^# added by nocobase-multicore install.sh/d' -e '/^COMPOSE_FILE=.*docker-compose.multicore.yml/d' "$PROJECT_DIR/.env"
      echo "   COMPOSE_FILE removed from $PROJECT_DIR/.env"
    fi
    FILES=""; OLDIFS=$IFS; IFS=,; for f in $CONFIG_FILES; do [ "$f" = "$OVERRIDE" ] || FILES="$FILES -f $f"; done; IFS=$OLDIFS
    echo "   removed $OVERRIDE; recreating the app with its original entrypoint..."
    # shellcheck disable=SC2086
    docker compose --project-directory "$PROJECT_DIR" $FILES up -d --remove-orphans "$SERVICE" >/dev/null 2>&1 && RESTORED=1 \
      || echo "   docker compose failed - run by hand: docker compose$FILES up -d --remove-orphans" >&2
    [ "$PURGE" = 1 ] && docker volume rm "${PROJECT}_multicore-redis-data" >/dev/null 2>&1 && echo "   Redis data volume removed" || true
  fi
fi
if [ "$PURGE" = 1 ]; then
  if [ "$MODE" = docker ] && [ "$RESTORED" = 1 ]; then
    NEW=$(docker compose --project-directory "$PROJECT_DIR" $FILES ps -q "$SERVICE" | head -1)
    docker exec "$NEW" sh -c 'rm -rf /app/nocobase/storage/multicore' && echo "   storage/multicore deleted"
  elif [ "$MODE" = docker ]; then
    echo "   --purge skipped: the container may still start through the supervisor; put the stock entrypoint back first"
  else
    run_in sh -c 'rm -rf storage/multicore' && echo "   storage/multicore deleted"
  fi
else
  echo "   storage/multicore/supervisor kept (harmless; delete with --purge)"
fi
if [ "$RESTORED" = 1 ]; then
cat <<'MSG'

Done. The plugins are removed and the app container was recreated with its original entrypoint: stock NocoBase again.
MSG
else
cat <<'MSG'

Plugins removed; NocoBase is running as a single process again and the site keeps working.
The supervisor files were left in place, so a restart of the container still works even if it still uses the supervisor
entrypoint. To go back to stock NocoBase completely:
  1. delete the `entrypoint:` line / the docker-compose.multicore.yml override (Docker) or start with `yarn start` (local),
  2. restart the app,
  3. optionally run  uninstall.sh --purge  to delete storage/multicore.
MSG
fi
